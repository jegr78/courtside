ALTER TABLE club_config
    ADD COLUMN waitlist_offer_minutes integer NOT NULL DEFAULT 15,
    ADD CONSTRAINT club_config_waitlist_offer_minutes_range CHECK (waitlist_offer_minutes BETWEEN 1 AND 1440);

CREATE TABLE waitlist_entry (
    id               uuid        PRIMARY KEY,
    account_id       uuid        NOT NULL REFERENCES user_account ON DELETE CASCADE,
    court_id         uuid        NOT NULL REFERENCES court,
    card_id          uuid        NOT NULL REFERENCES booking_card,
    starts_at        timestamptz NOT NULL,
    ends_at          timestamptz NOT NULL,
    note             text,
    state            text        NOT NULL,
    joined_at        timestamptz NOT NULL,
    joined_seq       bigint      GENERATED BY DEFAULT AS IDENTITY,
    offered_at       timestamptz,
    offer_expires_at timestamptz,
    closed_at        timestamptz,
    booking_id       uuid,

    CONSTRAINT waitlist_entry_period CHECK (ends_at > starts_at),
    CONSTRAINT waitlist_entry_state_known CHECK (
        state IN ('WAITING', 'OFFERED', 'BOOKED', 'LEFT', 'EXPIRED', 'SKIPPED', 'WITHDRAWN', 'ENDED')),
    CONSTRAINT waitlist_entry_open_until_closed CHECK (
        (state IN ('WAITING', 'OFFERED')) = (closed_at IS NULL)),
    CONSTRAINT waitlist_entry_offer_has_deadline CHECK (
        state <> 'OFFERED' OR (offered_at IS NOT NULL AND offer_expires_at IS NOT NULL)),
    CONSTRAINT waitlist_entry_offer_ends_by_start CHECK (
        offer_expires_at IS NULL OR offer_expires_at <= starts_at),
    CONSTRAINT waitlist_entry_booking_only_when_booked CHECK (booking_id IS NULL OR state = 'BOOKED'),
    -- One reservation per court and time, whoever's queue it came from.
    CONSTRAINT waitlist_entry_one_offer EXCLUDE USING gist (
        court_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (state = 'OFFERED'),
    -- One open wait per account, court and time, so nobody stacks offer windows over one court.
    CONSTRAINT waitlist_entry_one_open_per_account EXCLUDE USING gist (
        account_id WITH =,
        court_id WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (state IN ('WAITING', 'OFFERED'))
);

CREATE INDEX waitlist_entry_queue ON waitlist_entry (court_id, starts_at, joined_seq)
    WHERE state IN ('WAITING', 'OFFERED');
CREATE INDEX waitlist_entry_account ON waitlist_entry (account_id);
CREATE INDEX waitlist_entry_ends ON waitlist_entry (ends_at);

CREATE TABLE waitlist_participant (
    entry_id   uuid    NOT NULL REFERENCES waitlist_entry ON DELETE CASCADE,
    position   integer NOT NULL,
    kind       text    NOT NULL,
    person_id  uuid    REFERENCES person,
    guest_name text,
    card_id    uuid    REFERENCES participant_card,
    PRIMARY KEY (entry_id, position),
    CONSTRAINT waitlist_participant_kind_known CHECK (kind IN ('MEMBER', 'GUEST', 'CARD')),
    CONSTRAINT waitlist_participant_kind_matches_filler CHECK (
        (kind = 'MEMBER' AND person_id IS NOT NULL AND guest_name IS NULL AND card_id IS NULL)
        OR (kind = 'GUEST' AND person_id IS NULL AND guest_name IS NOT NULL AND card_id IS NULL)
        OR (kind = 'CARD' AND person_id IS NULL AND guest_name IS NULL AND card_id IS NOT NULL)
    )
);

CREATE INDEX waitlist_participant_person ON waitlist_participant (person_id) WHERE person_id IS NOT NULL;

