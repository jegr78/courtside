CREATE TABLE credit_account (
    account_id uuid PRIMARY KEY REFERENCES user_account (id)
);

CREATE TABLE credit_entry (
    id uuid PRIMARY KEY,
    position bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    account_id uuid NOT NULL REFERENCES credit_account (account_id),
    kind text NOT NULL,
    amount_minor integer NOT NULL,
    currency text NOT NULL,
    recorded_at timestamptz NOT NULL,
    recorded_by uuid,
    CONSTRAINT credit_entry_kind_sign CHECK (
        (kind = 'CREDIT' AND amount_minor > 0) OR (kind = 'PAYOUT' AND amount_minor < 0)),
    CONSTRAINT credit_entry_amount_bounded CHECK (amount_minor BETWEEN -1000000 AND 1000000),
    CONSTRAINT credit_entry_currency_code CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE INDEX credit_entry_account_position ON credit_entry (account_id, position);

CREATE TABLE credit_entry_note (
    entry_id uuid PRIMARY KEY REFERENCES credit_entry (id),
    reason_text text NOT NULL,
    CONSTRAINT credit_entry_note_length CHECK (length(btrim(reason_text)) BETWEEN 1 AND 200)
);

CREATE FUNCTION reject_credit_entry_change() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'credit_entry_append_only'
        USING ERRCODE = '23514', CONSTRAINT = 'credit_entry_append_only';
END;
$$;

CREATE TRIGGER credit_entry_append_only
    BEFORE UPDATE OR DELETE ON credit_entry
    FOR EACH ROW EXECUTE FUNCTION reject_credit_entry_change();
