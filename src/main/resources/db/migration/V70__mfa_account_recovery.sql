CREATE TABLE account_mfa_recovery (
    account_id uuid PRIMARY KEY REFERENCES user_account (id) ON DELETE CASCADE,
    recovery_id uuid NOT NULL UNIQUE,
    security_epoch bigint NOT NULL CHECK (security_epoch >= 0),
    address_hash varchar(64) NOT NULL CHECK (address_hash ~ '^[0-9a-f]{64}$'),
    code_hash varchar(64) UNIQUE CHECK (code_hash ~ '^[0-9a-f]{64}$'),
    expires_at timestamptz,
    created_at timestamptz NOT NULL,
    CHECK ((code_hash IS NULL) = (expires_at IS NULL))
);

