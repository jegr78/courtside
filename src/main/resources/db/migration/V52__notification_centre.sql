CREATE TABLE notification (
    id          uuid        PRIMARY KEY,
    account_id  uuid        NOT NULL REFERENCES user_account ON DELETE CASCADE,
    kind        text        NOT NULL,
    parameters  jsonb       NOT NULL DEFAULT '{}',
    created_at  timestamptz NOT NULL,
    created_seq bigint      GENERATED BY DEFAULT AS IDENTITY,
    read_at     timestamptz,

    CONSTRAINT notification_kind_known CHECK (
        kind IN ('CREDENTIALS_NEW_ACCOUNT', 'CREDENTIALS_PASSWORD_RESET', 'BOOKING_CONFIRMED',
                 'BOOKING_PLAYER_RECORDED', 'BOOKING_PLAYER_WITHDREW', 'BOOKING_DISPLACED',
                 'BOOKING_REMINDER', 'ACCOUNT_USERNAME_REMINDER', 'ACCOUNT_PASSWORD_RESET_CODE')),
    CONSTRAINT notification_parameters_named_strings CHECK (
        jsonb_typeof(parameters) = 'object'
        AND NOT jsonb_path_exists(parameters, '$.* ? (@.type() != "string")'))
);

CREATE UNIQUE INDEX notification_page_idx ON notification (account_id, created_seq DESC);

-- No row means the channel is on, which is how every account received mail before the choice existed.
CREATE TABLE message_channel_optout (
    user_account_id uuid        NOT NULL REFERENCES user_account (id) ON DELETE CASCADE,
    channel         text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_account_id, channel),
    CONSTRAINT message_channel_optout_channel_known CHECK (channel IN ('EMAIL'))
);
