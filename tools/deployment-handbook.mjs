import { spawnSync } from "node:child_process";
import { accessSync, constants, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { delimiter, isAbsolute, join } from "node:path";
import { fileURLToPath } from "node:url";

const allowedKeys = new Set(["schema", "ingress", "database", "mail"]);

function executable(name) {
  const found = (process.env.PATH ?? "").split(delimiter).filter(isAbsolute)
    .map((directory) => join(directory, name))
    .find((candidate) => {
      try {
        accessSync(candidate, constants.X_OK);
        return true;
      } catch {
        return false;
      }
    });
  if (!found) throw new Error(`${name} is not on an absolute PATH entry`);
  return found;
}

function parseRecipe(path) {
  const values = {};
  for (const [index, line] of readFileSync(path, "utf8").split("\n").entries()) {
    if (line === "" || line.startsWith("#")) continue;
    const match = /^([a-z]+)=([a-z0-9-]+)$/.exec(line);
    if (!match) throw new Error(`${path} line ${index + 1} is malformed`);
    const [, key, value] = match;
    if (!allowedKeys.has(key)) throw new Error(`${path} has unknown key ${key}`);
    if (Object.hasOwn(values, key)) throw new Error(`${path} declares ${key} twice`);
    values[key] = value;
  }
  for (const key of allowedKeys) {
    if (!Object.hasOwn(values, key)) throw new Error(`${path} declares no ${key}`);
  }
  if (values.schema !== "1") throw new Error(`${path} uses unsupported schema ${values.schema}`);
  return values;
}

function resolvedFiles(deploy, name) {
  const result = spawnSync(executable("bash"), [join(deploy, "recipe.sh"), "files", name],
    { encoding: "utf8" });
  if (result.status !== 0) throw new Error(`recipe ${name} did not resolve: ${result.stderr.trim()}`);
  return result.stdout.split("\n").filter(Boolean);
}

export function readRecipeCatalog(deploy) {
  return readdirSync(join(deploy, "recipes"))
    .filter((name) => name.endsWith(".recipe"))
    .map((file) => {
      const name = file.slice(0, -".recipe".length);
      return { name, ...parseRecipe(join(deploy, "recipes", file)), files: resolvedFiles(deploy, name) };
    })
    .sort((left, right) => left.name.localeCompare(right.name));
}

const labels = {
  en: {
    title: "Generated recipe commands",
    notice: "Generated from the recipe files consumed by the deployment CLI. Do not edit this file.",
    recipe: "Recipe",
    ingress: "Ingress",
    database: "Database",
    mail: "Mail",
    files: "Resolved Compose files",
  },
  de: {
    title: "Generierte Rezeptbefehle",
    notice: "Aus den Rezeptdateien der Deployment-CLI erzeugt. Bearbeite diese Datei nicht direkt.",
    recipe: "Rezept",
    ingress: "Webzugang",
    database: "Datenbank",
    mail: "E-Mail",
    files: "Aufgelöste Compose-Dateien",
  },
};

export function generatedRecipeMarkdown(deploy, locale) {
  const text = labels[locale];
  if (!text) throw new Error(`unsupported handbook locale ${locale}`);
  const catalog = readRecipeCatalog(deploy);
  const rows = catalog.map((recipe) => `| \`${recipe.name}\` | \`${recipe.ingress}\` | `
    + `\`${recipe.database}\` | \`${recipe.mail}\` |`).join("\n");
  const commands = catalog.map((recipe) => `## \`${recipe.name}\`\n\n`
    + "```sh\n"
    + `./recipe.sh files ${recipe.name}\n`
    + "```\n\n"
    + `${text.files}: \`${recipe.files.join(":")}\`.`).join("\n\n");
  return `# ${text.title}\n\n${text.notice}\n\n`
    + `| ${text.recipe} | ${text.ingress} | ${text.database} | ${text.mail} |\n`
    + "| --- | --- | --- | --- |\n"
    + `${rows}\n\n${commands}\n`;
}

export function assertGeneratedHandbooks({ deploy, english, siteEnglish, german }) {
  const targets = [[english, generatedRecipeMarkdown(deploy, "en")],
    [german, generatedRecipeMarkdown(deploy, "de")]];
  if (siteEnglish) targets.push([siteEnglish, generatedRecipeMarkdown(deploy, "en")]);
  for (const [path, expected] of targets) {
    if (readFileSync(path, "utf8") !== expected) {
      throw new Error(`generated handbook ${path} is out of date`);
    }
  }
}

function option(name) {
  const index = process.argv.indexOf(`--${name}`);
  if (index < 0 || index + 1 >= process.argv.length) throw new Error(`deployment-handbook needs --${name}`);
  return process.argv[index + 1];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const deploy = option("deploy");
  const english = option("english");
  const siteEnglish = option("site-english");
  const german = option("german");
  if (process.argv.includes("--write")) {
    writeFileSync(english, generatedRecipeMarkdown(deploy, "en"));
    writeFileSync(siteEnglish, generatedRecipeMarkdown(deploy, "en"));
    writeFileSync(german, generatedRecipeMarkdown(deploy, "de"));
  } else if (process.argv.includes("--check")) {
    assertGeneratedHandbooks({ deploy, english, siteEnglish, german });
  } else {
    throw new Error("Use --check or --write");
  }
}
